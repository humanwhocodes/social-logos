/**
 * @fileoverview Generates the SVG files and the React components.
 *
 * The vendored artwork in `vendor/logos/` is the single source of truth. Both
 * outputs are derived from it during the build, so the geometry for a logo is
 * never written down twice:
 *
 *   vendor/logos/<icon>.svg
 *     ├── src/svg/<slug>.svg      published as-is under the `/svg` entrypoint
 *     └── src/logos/<slug>.tsx    compiled into the React entrypoint
 *
 * Run with `npm run generate` (or indirectly via `npm run build`).
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { logos } from "./manifest.js";

//-----------------------------------------------------------------------------
// Paths
//-----------------------------------------------------------------------------

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = path.join(root, "vendor", "logos");
const svgDir = path.join(root, "src", "svg");
const logosDir = path.join(root, "src", "logos");
const indexPath = path.join(root, "src", "index.ts");

//-----------------------------------------------------------------------------
// Helpers
//-----------------------------------------------------------------------------

/**
 * Pulls the viewBox and the geometry out of a vendored SVG file. The `<title>`
 * is dropped because the components supply their own accessible name through
 * the `alt` prop, and a stray title would override it.
 * @param {string} svg The vendored file contents.
 * @param {string} name The file name, used for error messages.
 * @returns {{viewBox: string, content: string}} The extracted parts.
 */
function parse(svg, name) {
	const viewBox = /viewBox="([^"]+)"/u.exec(svg)?.[1];

	if (!viewBox) {
		throw new Error(`${name}: no viewBox found.`);
	}

	const content = /<svg[^>]*>([\s\S]*)<\/svg>/u
		.exec(svg)?.[1]
		.replace(/<title>[\s\S]*?<\/title>/gu, "")
		.trim();

	if (!content) {
		throw new Error(`${name}: no geometry found.`);
	}

	// The artwork must inherit color, so a hardcoded fill would defeat the
	// `fill` prop and the `currentColor` default.
	if (/\sfill="(?!none")/u.test(content)) {
		throw new Error(`${name}: geometry has a hardcoded fill.`);
	}

	return { viewBox, content };
}

/**
 * Converts SVG markup to JSX by camel-casing hyphenated attribute names.
 * @param {string} content The SVG markup.
 * @returns {string} Equivalent JSX.
 */
function toJsx(content) {
	return content.replace(
		/\s([a-z]+(?:-[a-z]+)+)=/gu,
		(_, attr) =>
			` ${attr.replace(/-([a-z])/gu, (__, letter) => letter.toUpperCase())}=`,
	);
}

/**
 * Builds a standalone SVG document for a logo. No `width` or `height` is
 * written, so the file scales to whatever the consumer sizes it to.
 * @param {string} viewBox The logo's viewBox.
 * @param {string} content The logo's geometry.
 * @returns {string} A complete SVG file.
 */
function toSvgFile(viewBox, content) {
	return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="currentColor">${content}</svg>\n`;
}

/**
 * Builds the React component module for a logo.
 * @param {import("./manifest.js").LogoEntry} logo The manifest entry.
 * @param {string} viewBox The logo's viewBox.
 * @param {string} content The logo's geometry.
 * @returns {string} The TSX source.
 */
function toComponentFile(logo, viewBox, content) {
	return `// Generated by scripts/generate.js. Do not edit.

import { Logo } from "../logo.js";
import type { LogoProps } from "../types.js";

/**
 * The ${logo.label} logo.
 * @param props Props for the logo.
 * @returns The rendered logo.
 * @see ${logo.url}
 */
export function ${logo.component}(props: LogoProps) {
	return (
		<Logo viewBox="${viewBox}" {...props}>
			${toJsx(content)}
		</Logo>
	);
}
`;
}

//-----------------------------------------------------------------------------
// Main
//-----------------------------------------------------------------------------

await fs.rm(svgDir, { recursive: true, force: true });
await fs.rm(logosDir, { recursive: true, force: true });
await fs.mkdir(svgDir, { recursive: true });
await fs.mkdir(logosDir, { recursive: true });

for (const logo of logos) {
	const file = path.join(vendorDir, `${logo.icon}.svg`);
	const { viewBox, content } = parse(await fs.readFile(file, "utf8"), file);

	await fs.writeFile(
		path.join(svgDir, `${logo.slug}.svg`),
		toSvgFile(viewBox, content),
		"utf8",
	);

	await fs.writeFile(
		path.join(logosDir, `${logo.slug}.tsx`),
		toComponentFile(logo, viewBox, content),
		"utf8",
	);
}

const exports = logos
	.map(logo => `export { ${logo.component} } from "./logos/${logo.slug}.js";`)
	.join("\n");

await fs.writeFile(
	indexPath,
	`// Generated by scripts/generate.js. Do not edit.

export type { LogoProps } from "./types.js";

${exports}
`,
	"utf8",
);

// Keep the human-readable inventory in sync with the manifest.
const rows = logos
	.map(
		logo =>
			`| [${logo.label}](${logo.url}) | \`${logo.component}\` | \`svg/${logo.slug}.svg\` |`,
	)
	.join("\n");

await fs.writeFile(
	path.join(root, "LOGOS.md"),
	`<!-- Generated by scripts/generate.js. Do not edit. -->

# Logos

${logos.length} logos. Each brand links to its official logo and trademark guidelines — review them before use.

| Brand | React component | SVG file |
| ----- | --------------- | -------- |
${rows}
`,
	"utf8",
);

console.log(`Generated ${logos.length} logos.`);
